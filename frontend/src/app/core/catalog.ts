export class CatalogLoader implements TranslateLoader {
  getTranslation(lang: string) {
    if (lang !== 'fr-SN' && lang !== 'en') return throwError(() => new Error('UNSUPPORTED_LOCALE'));
    return of(lang === 'en' ? en : fr);
  }
}
